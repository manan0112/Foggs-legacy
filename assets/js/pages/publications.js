function renderPublications() {
  const grid = document.querySelector(".pub-grid");
  if (!grid) return;

  const fragment = document.createDocumentFragment();

  PUBLICATIONS.forEach((pub, i) => {
    const a = document.createElement("a");
    a.className = "pub-card";
    a.href = pub.href;
    a.target = "_blank";
    a.rel = "noopener";

    const img = document.createElement("img");
    img.src = pub.img;
    img.alt = pub.alt;
    img.loading = pub.eager ? "eager" : "lazy";

    const title = document.createElement("p");
    title.className = "pub-card-title";
    title.textContent = pub.title;

    const author = document.createElement("p");
    author.className = "pub-card-author";
    author.textContent = pub.author;

    const date = document.createElement("p");
    date.className = "pub-card-date";
    date.textContent = pub.date;

    a.append(img, title, author, date);
    fragment.appendChild(a);
  });

  grid.appendChild(fragment);
}

document.addEventListener("DOMContentLoaded", renderPublications);
